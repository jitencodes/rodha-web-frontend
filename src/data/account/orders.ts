export function getAccountOrderById(id: string): AccountOrder | undefined {
  return ACCOUNT_ORDERS.find((order) => order.id === id);
}

export function getAccountOrdersByIds(ids: readonly string[]): AccountOrder[] {
  return ids
    .map((id) => getAccountOrderById(id))
    .filter((order): order is AccountOrder => Boolean(order));
}
